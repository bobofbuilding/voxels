// Each run owns a new database. DATABASE_URL is never used as a test target.
import pg from 'pg'
const { Client } = pg
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { randomBytes } from 'node:crypto'
import net from 'node:net'

function command(name, args, options = {}) {
  const result = spawnSync(name, args, { stdio: 'inherit', ...options })
  if (result.error) throw result.error
  if (result.status !== 0) throw new Error(`${name} exited with ${result.status}`)
}

let cluster
let started = false
let admin
let created = false
const name = `voxels_test_${randomBytes(6).toString('hex')}`
try {
  let url = process.env.TEST_DATABASE_URL
  if (!url) {
    cluster = mkdtempSync(join(tmpdir(), 'voxels-postgres-'))
    command('initdb', ['-D', join(cluster, 'data'), '-U', 'postgres', '-A', 'trust', '--no-locale', '--encoding=UTF8'], { stdio: 'pipe' })
    const port = await new Promise((resolve, reject) => {
      const socket = net.createServer()
      socket.on('error', reject)
      socket.listen(0, '127.0.0.1', () => {
        const address = socket.address()
        socket.close(() => resolve(address.port))
      })
    })
    command('pg_ctl', ['-D', join(cluster, 'data'), '-l', join(cluster, 'postgres.log'), '-o', `-h 127.0.0.1 -p ${port} -k ${cluster}`, '-w', 'start'])
    started = true
    url = `postgres://postgres@127.0.0.1:${port}/postgres`
  }
  admin = new Client({ connectionString: url })
  await admin.connect()
  await admin.query(`CREATE DATABASE ${name}`)
  created = true
  const target = new URL(url)
  target.pathname = `/${name}`
  const db = new Client({ connectionString: target.href })
  await db.connect()
  try {
    const schema = readFileSync('db/schema.sql', 'utf8')
    await db.query('CREATE EXTENSION citext')
    await db.query(schema.match(/CREATE TYPE public.avatar_type AS ENUM \([\s\S]*?\);/)[0])
    for (const table of ['avatars', 'favorites', 'reports', 'banned_users']) {
      let sql = schema.match(new RegExp(`CREATE TABLE public\\.${table} \\([\\s\\S]*?\\);`))[0]
      // These tests do not depend on UUID ordering; allow local PostgreSQL 16 too.
      sql = sql.replace('DEFAULT uuidv7()', 'DEFAULT gen_random_uuid()')
      if (table !== 'avatars') sql = sql.replace('id integer NOT NULL', 'id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      await db.query(sql)
    }
    await db.query('ALTER TABLE favorites ADD UNIQUE (wallet, token_id)')
  } finally {
    await db.end()
  }
  const result = spawnSync('pnpm', ['exec', 'vitest', 'run', '--config', 'vitest.database.config.ts'], {
    stdio: 'inherit',
    env: { ...process.env, NODE_ENV: 'test', DATABASE_URL: target.href, JWT_SECRET: randomBytes(32).toString('hex'), OWNER_ADDRESS: '0x134561f705A9C2DDA470b2246D075Bf7A3c612d2' },
  })
  if (result.error) throw result.error
  process.exitCode = result.status ?? 1
} catch (error) {
  console.error(error)
  process.exitCode = 1
} finally {
  try {
    if (created) await admin.query(`DROP DATABASE ${name} WITH (FORCE)`)
  } finally {
    await admin?.end()
    if (started) command('pg_ctl', ['-D', join(cluster, 'data'), '-m', 'immediate', '-w', 'stop'])
    if (cluster) rmSync(cluster, { recursive: true, force: true })
  }
}
